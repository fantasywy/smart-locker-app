//
// ⚠️ **文案集中在常量里，不散在 wxml 字面量中。** 理由与本仓库既有的两条纪律一致：
// 文案有唯一事实源，类型层与页面层都不该自己造词。
// 更实际的一条：失败出口的说明句是**定稿逐字**，把它拆进 `<view>` 标签里之后，
// 「有没有照抄」这件事就只能靠眼睛看 —— 而它恰恰是本票验收标准里的一条。

