// **金额展示** —— 全站唯一一次「分 → 元」换算（spec #57 §14.1）。
//
// ## 为什么必须只有一个工具
//
// 服务端所有金额字段的单位都是**分**（`payAmount` / `estimatedAmount` / `payments[].amount`），
// 而界面上只能出现「元」。分转元本身只有一行除法，正因为只有一行，它最容易在
// 每个消费页面各抄一遍 —— 抄错一次不会报错，只会让金额小一百倍或丢掉两位小数。
// 页面因此**不写任何 `/ 100`**，只调用 `formatMoney()`。
//
// ## 写法逐字（spec §14.1）
//
//   • `¥12.00` / `¥1,234.56` —— `¥` 前缀、**两位小数**、整数部分**千分位**；
//   • 不写「元」字。
//
// ⚠️ **不读、不猜、不缓存任何金额**：它只做格式化，输入输出都是纯函数。
// 金额是否该展示、该用「参考金额 / 实付 / 已付 / 本次支付」里的哪个词，
// 由页面与文案层决定 —— 这里只负责把分写成人看得懂的字符串。

/**
 * 把**分**格式化成 `¥` + 两位小数 + 千分位。
 *
 * @param cents 服务端金额字段的原始值（单位：分）
 * @returns `¥12.00` / `¥1,234.56`；输入不是有限数时返回空串（页面不渲染这一块）
 *
 * ⚠️ **只做一次除法**：`cents / 100`。再除一次不会报错，只会让金额小一百倍。
 * ⚠️ 用 `toFixed(2)` 而不是 `Math.round` 之后自己补零：后者在 `1200` 这类整元上
 * 会输出 `¥12`，而界面的金额必须始终有两位小数。
 */
export function formatMoney(cents: number): string {
  if (!Number.isFinite(cents)) return ''

  const yuan = cents / 100
  const [integer, decimals] = yuan.toFixed(2).split('.')
  // `toFixed` 对有限数一定带小数点，所以这里两个分支都只会取到真值；
  // 用 `?? ''` 只是为了在 strict TS 下不引入非空断言。
  const grouped = (integer ?? '').replace(/\B(?=(\d{3})+(?!\d))/g, ',')
  return `¥${grouped}.${decimals ?? '00'}`
}
