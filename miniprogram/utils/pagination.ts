// **列表分页尾部** —— 三条分页规则只写一次。issue #23 的交付物之一。
//
// 契约出处：`docs/spec/03-order-list.md` §1.9 + §7（订单列表）、
// `docs/spec/05-reservation.md` §6.3（预约列表）、
// `docs/spec/04-blacklist-and-degradation.md` §7.3（信用分明细）。
// ⚠️ 三处的规则**逐字相同**，本模块是它们唯一的实现处：
//
//   首屏 `pageSize = 20`（`status` 不传）· 上拉触底取下一页
//   · **终止条件 = 已加载条数 ≥ `total`**
//   · `onShow` / 下拉刷新 = 静默刷新并**重置回第一页**（丢弃已加载的后续页）
//   · 不做常驻轮询
//
// ## 为什么「终止条件」值得单独一个模块
//
// 因为**唯一自然想到的写法是错的**，而错了的症状是「列表能跑、只是到底了还在转」。
//
// 直觉写法是「返回空数组 = 没有下一页了」。⚠️ 那在本后端**永远不成立**：
// `03` §1.9 逐字 ——「**分页越界钳制到末页**（`PageSupport`，缺省 `pageSize = 20`、
// 上限 100）—— 『请求越界页返回空列表』**不会发生**」。越界请求会**重复返回末页**，
// 于是「按空数组判断」的实现会**无限重复末页**：用户一直上拉，同一页数据一遍遍接在后面。
//
// ⇒ 唯一正确的判据是 **`已加载条数 ≥ total`**。这个数由服务端在响应里给，
// 客户端只做一次比较 —— 不推断、不补算。
//
// ## 形态：纯函数 + 状态，不是组件
//
// 上拉加载的**触发器**（`onReachBottom`）天然属于页面，不是组件能接住的；
// 而三条口径里真正需要「只写一次」的是**状态推进**（首屏 / 追加 / 重置 / 还该不该再拉）。
// 把它做成纯函数，页面拿到的就是「拉完这一页之后我该显示什么、还能不能再拉」，
// 三个页面因此共用同一份推进逻辑，而各自的 wxml 版式可以完全不同
// （订单行 / 预约行 / 明细行本来就是三种版式）。
//
// ⚠️ 本模块是纯函数，不碰 `wx.*`、不碰请求层（`07` §3 `utils/` 的定位）——
// 「怎么发请求」是页面与 `api/` 的事，本模块只回答「发完回来了，状态怎么变」。

/**
 * 首屏每页条数 —— `03` §7 / `05` §6.3 / `04` §7.3 三处一致，**且是服务端缺省**。
 *
 * ⚠️ 它是「服务端缺省」而不是「客户端偏好」：`03` §7 那一行原文是
 * 「`pageSize = 20`（**服务端缺省**）」。所以这个 20 不是我们挑的一个数，
 * 是**契约事实**的登记。改它要同时改三份 spec。
 *
 * ⚠️ 上限是 100（`03` §1.9）—— 本常量远在下限一侧，这里不做出参数校验：
 * 它是**常量**，不是运行时旋钮，一个「可能传错」的口子不需要防。
 */
export const PAGE_SIZE = 20

/**
 * 分页状态 —— 一个列表「现在装了多少、总共多少、还能不能再拉」的全部信息。
 *
 * ⚠️ `items` 在这里是 `readonly T[]` 而**不是**页面 `data` 里的那个数组：
 * 本模块只做状态推进，`setData` 是把结果交回页面之后的事。让纯函数去碰 `setData`
 * 就等于把它绑死在页面实例上，也就测不动了。
 *
 * ⚠️ **它带一个 `page` 字段，而且那个字段不是 `items.length` 的函数。**
 * 由长度反推页码（`floor(len / PAGE_SIZE) + 1`）在**末页不满**时会算出**已经拉过的那一页** ——
 * 而末页不满是常态。详见 `nextPage()` 的说明：那是与「按空数组判断」同症状的第二种缺陷。
 * 它长在 `PagedList` 上而不是页面 `data` 里的一个变量，正因为
 * `applyFirstPage` / `appendPage` 是仅有的两个写入口，它**不可能**与 `items` 不同步。
 */
export interface PagedList<T> {
  /** 已加载的全部条目 —— 首屏 + 各次追加的结果，顺序与服务端一致。 */
  readonly items: readonly T[]
  /**
   * 服务端给的总条数（响应里的 `total`）。
   *
   * ⚠️ 首屏之前是 `0`，而 `0` 恰好也是「一条都没有」的真实取值 —— 两者由
   * `PagedList.loaded` 区分，**不由 `total` 区分**。这个区分是有意的：
   * 「还没拉过」显示骨架屏，「拉过且 total 为 0」显示空态，两种画面完全不同（`09` §7.1）。
   */
  readonly total: number
  /** 是否已经完成过至少一次请求 —— 区分「还没拉」与「拉完是空的」。 */
  readonly loaded: boolean
  /**
   * **已经请求到第几页**（服务端页码从 1 开始）。
   *
   * ⚠️ 初态是 `0`：**一页都还没请求过**。于是 `nextPage()` 给出 1 —— 首屏要的就是第 1 页。
   * （若初态写成 1，首屏就会去拉第 2 页，而第 1 页永远不会被加载。）
   */
  readonly page: number
}

/** 一个列表的初始状态 —— 首屏请求发出**之前**。 */
export function createPagedList<T>(): PagedList<T> {
  return { items: [], total: 0, loaded: false, page: 0 }
}

/**
 * 首屏（或 `onShow` / 下拉刷新后的**重置**）—— 用服务端返回的第一页**替换**全部内容。
 *
 * 契约：`03` §7 的 `onShow` 行「**静默刷新并重置回第一页**（丢弃已加载的后续页）」
 * （`05` §6.3 同）；`03` §7 的「**重置而非增量刷新**」那条理由逐字：
 *
 * > 在途单的状态会在翻页之间变，保留陈旧后续页等于让列表撒谎。
 *
 * ⚠️ 所以「刷新」在本模块里**只有这一个入口**，而且它是 `replace` 不是 `merge`——
 * 不提供「保留已加载页再补第一页」的写法，那种写法正是 `01` §3.2 禁止的本地缓存。
 *
 * ⚠️ 它把 `page` **归到 1**，这也是「重置」那一半的落地：只清 `items` 而不归页码，
 * 下一次上拉会去请求第 N 页而列表里只有第 1 页 —— 中间整段凭空消失。
 */
export function applyFirstPage<T>(page: PageOf<T>): PagedList<T> {
  return { items: [...page.records], total: page.total, loaded: true, page: 1 }
}

/**
 * 追加一页（上拉触底加载更多）—— 把新一页接在已加载的后面。
 *
 * ⚠️ **不在这里判断「该不该拉」** —— 那是 `canLoadMore()` 的事，调用方在发请求**之前**
 * 问它。若在这里也判一次，同一条件就有两个实现处，而两者的更新时机不同
 * （一个在请求前、一个在响应后），迟早会漂移成「按钮说能拉、拉回来发现不该拉」。
 *
 * ⚠️ `page` 前进一 —— 调用方请求的是 `nextPage(state)` 那一页，`appendPage` 记的就是它。
 */
export function appendPage<T>(state: PagedList<T>, page: PageOf<T>): PagedList<T> {
  return {
    items: [...state.items, ...page.records],
    // ⚠️ `total` 取**最新响应**的值而不是保留第一次的：total 会随状态推进而变
    // （新单进来、订单被清理）。用陈旧的 total 判断终止条件，会在总数变大之后
    // 提前停止加载 —— 列表看起来「就是这些了」，其实还有。
    total: page.total,
    loaded: true,
    page: state.page + 1,
  }
}

/**
 * 服务端返回的一页 —— 三个列表端点的响应里都有的那两个字段。
 *
 * ⚠️ 刻意只声明 `records` 与 `total` 两项：`03` / `05` / `04` 三处响应外层还各带
 * `page` / `pageSize` 之类，但**推进逻辑一个都不用**。少声明一个字段，就少一处
 * 「拿服务端的页码跟我们本地算的对一对」的机会 —— 那种对账是双源真相的入口。
 */
export interface PageOf<T> {
  /** 本页条目。⚠️ 越界时**不是空的** —— 服务端会钳制到末页（`03` §1.9）。 */
  readonly records: readonly T[]
  /** 服务端给的总条数。终止条件只认它。 */
  readonly total: number
}

/**
 * 还能不能继续上拉加载 —— **`03` §7 / `05` §6.3 / `04` §7.3 的终止条件**。
 *
 * 判据只有一条：
 *
 *     已加载条数 ≥ total  ⇒  到底了
 *
 * ⚠️⚠️ **不得改写成「上一页返回空数组就停」。** `03` §1.9 逐字：分页越界**钳制到末页**，
 * 「请求越界页返回空列表」**不会发生**。按空数组判断的实现会在末页之后
 * **无限重复末页** —— 上拉一次、末页数据再接一遍。本仓库有一条 Vitest 用例
 * 专门喂「非空的重复末页」当反例把它钉住（`test/utils/pagination.test.ts`）。
 *
 * ⚠️ `loaded === false`（首屏还没回来）时返回 `false` —— 还没拉过就没有「更多」可言，
 * 此时上拉应当被页面忽略。⛔ **不要**把它当成「一个都用不着」而删掉：
 * `items.length >= total` 在初态下是 `0 >= 0` = `true`，恰好也返回 `false`，
 * 但那是**巧合而非理由**（一旦初态的 `total` 变成 `-1` 之类的哨兵值就会翻）。
 * 显式写出来，让「首屏没回来时不能上拉」是一条被声明的规则。
 */
export function canLoadMore<T>(state: PagedList<T>): boolean {
  if (!state.loaded) return false
  return state.items.length < state.total
}

/**
 * 下一页的页码 —— 服务端页码从 **1** 开始（`03` §7 的「重置回第一页」即 `page = 1`）。
 *
 * 只有在 `canLoadMore()` 为真时调用它才有意义 —— 到底之后再拉就是那个无限重复末页的缺陷
 * （回末页、判「非空 ⇒ 还有」、再接一遍）。
 *
 * ## ⚠️ 为什么这里**必须**存一个 `page`，而不是由 `items.length` 推出来
 *
 * 第一版就是推出来的：`Math.floor(len / PAGE_SIZE) + 1`。它在**末页不满**时会算错，
 * 而末页不满是常态不是特例。`total = 45` 时实际装载是 20 + 20 + **5**，
 * 推出来的下一页却是 `floor(45/20)+1 = 3` —— 也就是**再拉一次第 3 页**，
 * 而那正是刚刚才拉过的那一页。列表于是把末页 5 条又接一遍。
 *
 * ⚠️ 这与「按空数组判断」是**两种不同的缺陷，同一个症状**：都是「到底了还在重复末页」。
 * 区别在于空数组那个是判据错，这个是**推导式错** —— 而推导式错的版本更隐蔽，
 * 因为它在「每页都满」的假数据下完全正确（本仓库的用例正是拿 45 条这种不满的末页
 * 把它抓出来的）。
 *
 * ⇒ 「当前已请求到第几页」是一个**独立事实**，不是长度的函数（长度丢掉了
 * 「最后一页装了几条」这个信息）。所以它作为状态显式存住，由 `applyFirstPage` /
 * `appendPage` 维护 —— 那两个函数是仅有的两个写入口，因此它不可能与 `items` 不同步。
 */
export function nextPage<T>(state: PagedList<T>): number {
  return state.page + 1
}
