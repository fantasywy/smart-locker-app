// 认证端点（`13.1` 登录 / `13.2` 刷新）的**手写 DTO** —— 类型层的第一个模块。
//
// 契约源：`java/smart-locker/docs/API设计文档.md` v1.0
//   • §1.4.2 用户端微信登录 + 双 token（:60-64）
//   • §13.1 登录 `POST /api/app/v1/auth/login`（:919-939）
//   • §13.2 刷新 `POST /api/app/v1/auth/refresh`（:941-943）
//   • §1 认证总则「除 13.1/13.2 外均需 Authorization: Bearer <accessToken>」（:917）
//   • §15 错误码表（:1307-1308）
// 字段级出处的底稿：`docs/research/R1-api-mapping.md` §1「13.1 / 13.2」。
//
// 承 `07` §7（类型来源）的规则，本模块是它们的落地：
//   1. **不发明字段、不改字段名、不合并语义不同的字段** —— 后端叫 `accessToken` 就叫 `accessToken`。
//   2. **可空字段显式标 `| null`** —— strict 模式因此强迫调用方处理这些分支。
//   3. **枚举值与后端逐字一致** —— `NORMAL` / `BLACKLISTED` 原样进类型。中文映射属 `09`
//      文案层（`09` §0 硬规则 1、§8），**不进这里**：类型层是后端的形状，文案层是用户的语言。
//   4. **找不到契约依据的字段不写** —— 宁可缺，不可编。本模块因此**没有** `13.2` 的
//      `refreshToken`（契约里根本没有它，只有 `accessToken` / `expiresIn`）。
//
// ⚠️ 本模块**只有形状，没有行为**。它是纯类型声明 + 不产出任何运行时代码，因此可以被
// `import type` 从任何一端消费，也**不含任何 `wx.*` 调用**（发请求是 `request/` + `api/` 的事，
// 承 `07` §3 硬规则 1）。

/**
 * `13.1` 请求体 —— `POST /api/app/v1/auth/login`。
 *
 * 契约：API设计文档.md §13.1 (:922-927)
 * 出处底稿：`R1` §1「13.1 · 请求字段」、`docs/spec/01-entry-and-identity.md` §3.1（隐式前置登录）
 *
 * 请求体的字段与默认取值：`code` 必填，其余三项一期不填（见各字段注释）。
 */
export interface LoginRequest {
  /**
   * 微信侧登录凭证（`wx.login` 取得的临时 `code`）—— **必填**，也是本请求唯一的必需字段。
   *
   * ⚠️ 它不是「校验失败就 `1001`」的普通参数：`code` 为空或无效由**换取通道**判为 `8001`
   * （HTTP 200、业务错误，见 §15 :1307），**不是** `1001` 参数校验错
   * （后端源码口径：`AppLoginRequest` 的 Javadoc「空值/无效由换取通道判为 8001（不是 1001）」）。
   * 后果：登录失败在统一异常对象里长成 `kind: 'business'`，**不是** `unauthorized` —— 这一条
   * 由 `#18` 的归一化测试锁住。
   */
  code: string

  /**
   * 微信授权昵称 —— **可选**，仅首次自动注册时落库（§13.1 :927）。
   *
   * ⚠️ 一期**不填**这三项：资料填写归 `01` §5「我的」页的头像昵称填写能力。本字段存在
   * 只是为了让类型与契约逐字一致，「类型上有」不等于「一期要传」。
   */
  nickname?: string

  /** 微信授权头像 URL —— **可选**，同上（§13.1 :927）。 */
  avatar?: string

  /** 微信授权手机号 —— **可选**，同上（§13.1 :927）。⚠️ `01` §8 明确「不展示手机号」。 */
  phone?: string
}

/**
 * 用户状态枚举 —— **值与后端逐字一致**，不做任何中文映射。
 *
 * 契约：API设计文档.md §13.1 (:934, :939)
 * 后端真源：`UserStatus`（`NORMAL` / `BLACKLISTED`）；`09` §1 的信用分行状态语义
 * （`NORMAL` → 中性档；`BLACKLISTED` → 警示档）**是文案层的映射，不在此处**。
 */
export type UserStatus = 'NORMAL' | 'BLACKLISTED'

/**
 * `13.1` 响应 `data.user` —— 登录时刻的用户简要信息。
 *
 * 契约：API设计文档.md §13.1 (:934-935)
 * 出处底稿：`R1` §1「13.1 · 响应 data」（含各字段的可空判定）
 */
export interface LoginUser {
  /**
   * 用户 ID。不可空。
   *
   * ⚠️ **`number` 是对 Java `Long` 的有意收窄**（后端 `AppUserBriefVO.id` 是 `Long`）。
   * 契约示例给的是 `88`，且已核实后端**没有** Long→String 的序列化定制（`JacksonConfig` /
   * `application.yaml` 均无），因此 JSON 里它就是数字。理论上 `Long` 可超
   * `Number.MAX_SAFE_INTEGER`（2^53−1），本端会丢精度 —— 但这是数据库自增主键，现实里到不了，
   * 且用 `string` 会与契约示例、与全站 `id: number` 的形状分叉。
   * **这是一条登记在案的假设，不是疏漏**；若后端 ID 策略改为雪花 ID，此处须重新裁决。
   */
  id: number

  /** 昵称。**可空** —— 未授权资料时为空（§13.1 :934；`R1` 标 `[可空]`）。 */
  nickname: string | null

  /** 头像 URL。**可空** —— 同上。 */
  avatar: string | null

  /** 手机号。**可空** —— 同上。⚠️ 即便有值，`01` §8 也规定不展示。 */
  phone: string | null

  /**
   * 信用分（后端字段 `score`）。不可空 —— 首次自动注册时取系统参数 `score.max`（默认 100，§13.1 :939）。
   *
   * ⚠️ 术语纪律：它是**信用分**，**不叫「积分」** —— 它不是可兑换的消费积分，而是扣减型的
   * 行为约束分（`CONTEXT.md`「信用分」：`_Avoid_: 积分、评分、分值`）。
   */
  score: number

  /**
   * 用户状态。**不可空** —— 但值本身带一个必须写死的陷阱，见下。
   *
   * ⚠️⚠️ **登录成功时它也可能是 `BLACKLISTED`。**
   *
   * 契约原文：`13.1`「**黑名单用户允许登录**（`status` 返回 `BLACKLISTED`，下单等操作另行拦截）」
   * （§13.1 :939）。`01` §1 第 4 条同（「**黑名单用户允许登录**（`status = BLACKLISTED`）
   * ⇒ **不存在「登录被拒」的业务分支**」）。也就是说 `status` 与「这次登录成不成功」
   * **完全正交** —— 它描述的是这个账号当前的受限状态，不是登录的结果。
   *
   * ⚠️ 上面引的「黑名单」是**后端契约原文**，照引不误；但**用户可见文案里不出这个词**，
   * 一律说「受限」（`09` §8 禁用词表、`CONTEXT.md`「受限」：`_Avoid_: 封号、被拉黑、被禁止`）。
   * 本文件是类型层、不是文案层，所以引用照原文；写下游文案时换成「受限」。
   *
   * ⚠️ **客户端不得据此做任何事前阻断**（`04` §5：「拦截权只能属于服务端」）：
   *   1. `status` 是**登录时刻的快照** —— 解除后、刚被限制时都可能过期。在本地据此拦，
   *      会造出「本地说不让、服务端其实让」的**双源真相**，最坏的情况是**把已经解禁的用户
   *      挡在门外**。
   *   2. 受限动作「**一律保持可见、可点、点击后解释**」（`04` §5.1）—— 不置灰、不隐藏、
   *      不跳受限页。受限卡的解释留到**动作点**：`5004` 由请求层特判成 `kind: 'restricted'`
   *      （`07` §4.2），文案走 `04` §5.1 / `09` §3。
   *   3. 因此**本层只把它作为字段带住**，判断权交给后续动作点。
   *
   * 后来者最容易在这里加一个「`BLACKLISTED` 就跳受限页」的早退分支 —— 那正是 `04` §5 第 1 条
   * 明令禁止的。**本字段的正确用法是「只读、不判断」。**
   */
  status: UserStatus
}

/**
 * `13.1` 响应 `data` —— `POST /api/app/v1/auth/login`。
 *
 * 契约：API设计文档.md §13.1 (:929-939)
 * 出处底稿：`R1` §1「13.1 · 响应 data」
 *
 * ```json
 * { "accessToken": "xxxx", "refreshToken": "yyyy", "expiresIn": 7200,
 *   "user": { "id": 88, "nickname": "小明", "avatar": "https://...", "phone": "13900000000",
 *             "score": 95, "status": "NORMAL" } }
 * ```
 */
export interface LoginResponse {
  /**
   * 访问令牌。随业务请求走 `Authorization: Bearer <accessToken>`（§13 总则 :917）。
   * 有效期 2h（§1.4.2 :63）。不可空。
   */
  accessToken: string

  /**
   * 刷新令牌。仅在调用 `13.2` 时以 **`X-Refresh-Token` 头**送出
   * （§13.2 :943）—— **不是** Bearer access。有效期 30 天（§1.4.2 :63）。
   *
   * ⚠️ 它**只在 `13.1` 的响应里出现**。`13.2` 的响应**没有**这个字段（见 `RefreshResponse`）。
   */
  refreshToken: string

  /**
   * access 的剩余有效秒数（契约示例 `7200`）。
   *
   * ⚠️ **契约里有，但 C 端不消费**：`07` §4.4 已定案「**不在本地预判过期**、不记 `expiresIn`、
   * 不比对本地时钟，完全靠 401 驱动」—— 本地时钟偏移会误刷或漏刷，而 401 才是权威信号。
   * 本字段落进类型层是为了**如实反映后端的形状**，**不是**给实现者拿来算过期的。
   */
  expiresIn: number

  /** 登录时刻的用户简要信息。不可空。 */
  user: LoginUser
}

/**
 * `13.2` 响应 `data` —— `POST /api/app/v1/auth/refresh`。
 *
 * 契约：API设计文档.md §13.2 (:941-943)
 * 出处底稿：`R1` §1「13.2 · 响应 data」
 *
 * ```json
 * { "accessToken": "xxxx", "expiresIn": 7200 }
 * ```
 *
 * ⚠️⚠️ **此响应里没有 `refreshToken` —— 类型层不得凭空补上。**
 *
 * `13.2` 是**续期 access**，不轮换 refresh：refresh 30 天有效、可主动作废（登出），
 * 与 access 是两套生命周期。因为契约里根本没有这个字段，实现者**不得**用
 * 「整个 `data` 覆盖回 token 结构」的写法 —— 那样会把 refresh 写成 `undefined`，
 * 下一次请求就会提前撞上 `401 + 2005`（refresh 失效）而被迫重登，
 * 把一个 30 天的会话缩成一次刷新。
 *
 * 正确做法：**只更新 access，刷新令牌原值保留**（`07` §4.4 的 token 持久化口径）。
 * 这条由 `#19` 的测试锁住（断言处理完刷新后 `storage` 里的 refresh 原值不变）。
 */
export interface RefreshResponse {
  /**
   * 新的访问令牌。同 `LoginResponse.accessToken`，走 `Authorization: Bearer <accessToken>`。
   * 不可空。
   */
  accessToken: string

  /**
   * 新 access 的有效秒数（契约示例 `7200`）。
   *
   * 与 `LoginResponse.expiresIn` 同一条口径：**契约里有，C 端不消费**（`07` §4.4 不预判过期）。
   */
  expiresIn: number
}
