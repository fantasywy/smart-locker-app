// `GET /contents/{key}` 的**手写 DTO** —— 只做形状，没有行为。
//
// 契约：spec #57 §13「新端点（后端待建）」
//   `GET /api/app/v1/contents/{key}`（**免鉴权**）→ `{ key, title, updatedAt, blocks[] }`
//   block 只有三种：`heading{text}` / `paragraph{text}` / `qa{question,answer}`。
//
// ⚠️ **内容正文归后端维护，不进 `startup/copy.ts`。** 文案层管的是界面文案
// （标题、按钮、失败提示），内容层管的是「这一页讲什么」。把正文抄进类型层或文案层
// 等于让服务端下发的内容在客户端有第二个家 —— 后端改价 / 改规则后，用户会看到旧版本。
//
// ⚠️ **内容维护口径（服务端内容作者的验收点，本仓库无法代测）**：
//   • `billing`：只讲规则（关门落定起算、按小时、峰 / 非峰 / 超时、5 分钟向上取整、
//     取件时结算、超时补缴差额、参考金额 ≠ 实付），**不得写任何具体价格**；
//   • `faq`：至少覆盖 7 个主题 —— 存件 / 取件与取件码 / 费用与支付时机 / 超时 /
//     预约与爽约失效 / 柜门打不开 / 柜机故障；
//   • 两页都**不出现发票、优惠券**。
// 这些是内容层数据，不在客户端源码里；客户端只负责按 block 排版与失败重试。
//
// ⚠️ 本模块遵守类型层的五条规则：不发明字段、不改字段名、不合并语义不同的字段、
// 可空显式标 `| null`、枚举值与后端逐字一致、**找不到契约依据的字段不写**。

/**
 * 内容页的两个固定 key —— 契约里**只有**这两个。
 *
 * ⚠️ 页面不接收路由参数来决定 key：计费页永远取 `billing`、FAQ 页永远取 `faq`。
 * 把 key 变成页面参数会打开「任意 key」的入口，而服务端对未知 key 只回 `404 + 1002`。
 */
export type ContentKey = 'billing' | 'faq'

/**
 * 内容块 —— 契约定义的**三种**排版单元。
 *
 * ⚠️ `type` 是判别键：界面按它选择标题 / 段落 / 问答三套排版之一。
 * 不要新增第四种「富文本 / HTML」：内容端点只承诺这三个形状，页面也不解析 HTML。
 */
export type ContentBlock =
  | {
      /** 小标题 —— 渲染为章节标题。 */
      type: 'heading'
      /** 标题文本（服务端下发，客户端不翻译、不拼接）。 */
      text: string
    }
  | {
      /** 正文段 —— 渲染为一段正文。 */
      type: 'paragraph'
      /** 段落文本（服务端下发）。 */
      text: string
    }
  | {
      /** 问答 —— 问题 + 答案。 */
      type: 'qa'
      /** 问题文本。 */
      question: string
      /** 答案文本。 */
      answer: string
    }

/**
 * `GET /contents/{key}` 响应 `data`。
 *
 * ```json
 * { "key": "billing", "title": "计费说明", "updatedAt": "2026-10-23T12:00:00+08:00",
 *   "blocks": [{ "type": "heading", "text": "计费规则" }] }
 * ```
 */
export interface ContentResponse {
  /** 回显请求的 key。页面不拿它做跳转判断 —— 两个页面各自只请求自己那一个。 */
  key: ContentKey

  /**
   * 内容的标题。⚠️ **页面不把它用于导航栏**：导航栏标题按 spec §10 取 `PAGE_TITLES`。
   * 字段保留是为了如实反映契约，也便于将来做页面内说明；不做展示。
   */
  title: string

  /** 内容最后更新时间（服务端时间）。一期不展示，保留契约形状。 */
  updatedAt: string

  /** 内容块，按服务端给定顺序渲染。 */
  blocks: ContentBlock[]
}
