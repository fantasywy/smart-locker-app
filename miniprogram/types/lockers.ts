// `13.6` 扫码查柜机的**手写 DTO** —— 只做形状，没有行为。
//
// 契约：API设计文档.md §13.6 `GET /api/app/v1/lockers/by-code` (:1088-1103)
//
// ⚠️ 本模块遵守**类型层与请求层分离**的硬规则（「`types/` 与 `api/` 一一对应 ——
// 一个端点模块配一个 DTO」）。对应的端点函数在同名的
// `api/` 模块里，**两者一一对应**：
//
//     types/lockers.ts   ← 形状（本文件，纯类型，编译后不产出可执行代码）
//     api/lockers.ts     ← 搬运（入参 → 请求 → 出参 DTO）
//
// ⚠️ 本模块遵守类型层的五条规则：不发明字段、不改字段名、不合并语义不同的字段、
// 可空显式标 `| null`、枚举值与后端逐字一致、**找不到契约依据的字段不写**。
// 中文映射属文案层，**不进类型层**。

/**
 * 柜机状态枚举 —— **数字码，值与后端逐字一致**（spec #57 §3「数值柜机状态」）。
 *
 * 契约：API设计文档.md §13.6 (:1097)
 * 后端真源：`LockerStatus` 的 `1`(ONLINE) / `2`(OFFLINE) / `3`(FAULT) / `4`(MAINTAINING)。
 *
 * ⚠️⚠️ **这里曾是三档字符串时代留下的 `'ONLINE' | 'OFFLINE' | ...`**。
 * 后端 `/v3/api-docs` 与 13.6 示例都是**数字码**（示例 `"status": 1`）；
 * spec #57 §3 的「实现前置（契约漂移）」明确要求以 API 文档为准。
 * 保留字符串枚举会让页面在运行时拿到 `1` 却拿 `'ONLINE'` 去比 —— 恒不相等，
 * 且 TS 不会报错（服务端返回的类型本来就是我们自己声明的）。
 *
 * ⚠️ 中文映射属文案层，**不进这里**；页面也不拿它做可用性判断（见 `online`）。
 */
export type LockerStatus = 1 | 2 | 3 | 4

/**
 * 四档余位计数 —— `{ small, medium, large, extraLarge }`（契约 §13.6 :1098）。
 *
 * 契约：API设计文档.md §13.6 (:1098,:1101)
 *
 * ⚠️⚠️ 这里有两套**不同写法**，它们不是同一套：
 *
 * | 出处 | 形状 | 例 |
 * |---|---|---|
 * | `13.6` 响应 `cellAvailability` 的键 | **小写阶名** | `extraLarge` |
 * | `13.7` 请求体 `cellType` | **数字码 1–4** | `4` |
 * | 用户看到的字 | 中文 | 「特大格口」 |
 *
 * 三者的对应关系收在柜机页的**一张档位表**里（`CELL_TYPES`），
 * 任何一处 `[type]` / `toUpperCase()` / 字符串枚举的「顺手转换」都绕过它。
 * 绕过的那次会在某个档位上静默取到 `undefined`（`undefined === 0` 为 `false`），
 * 于是**该灰的不灰**，用户点下去才撞 `8002`。
 *
 * ⚠️ **柜机非 `ONLINE` 时四项恒为 0 且不报错**（`:1101-1103`）——
 * 那是**正常响应而非错误**。⇒ 类型上它就是 `number`，**不是** `number | null`：
 * 「0」是一个有意义的、服务端明确回显过的值（该规格已满），把它当缺失处理会
 * 让页面走上「数据没回来」那条路，而用户看到的是一个错误态。
 */
export interface CellAvailability {
  /** 小格口空闲计数。⚠️ 小写阶名。契约 §13.6 (:1098)。 */
  small: number
  /** 中格口空闲计数。⚠️ 小写阶名。契约 §13.6 (:1098)。 */
  medium: number
  /** 大格口空闲计数。⚠️ 小写阶名。契约 §13.6 (:1098)。 */
  large: number
  /**
   * 特大格口空闲计数 —— 四档改造新增的第四键（契约 §13.6 :1098）。
   *
   * ⚠️ 服务端保证四键**恒齐全**（缺类型补 `0`，`:1101`），所以这里不是可选字段。
   * 缺了它，第四档的余位会静默读成 `undefined`。
   */
  extraLarge: number
}

/**
 * `13.6` 响应 `data` —— 一台柜机的全部可得信息。
 *
 * 契约：API设计文档.md §13.6 (:1091-1103)
 *
 * ```json
 * { "id": 11, "code": "WD-01", "siteId": 3, "siteName": "望京 SOHO T1",
 *   "position": "B1 层 3 号电梯口", "online": true, "status": 1,
 *   "cellAvailability": { "small": 4, "medium": 2, "large": 0, "extraLarge": 0 } }
 * ```
 *
 * ⚠️ **`siteId` 有，但本页不用**（柜机页的渲染清单里没有它）。
 * 它留在类型里是为了**如实反映后端形状**（「不发明、不改名」），
 * 而不是给实现者一个「顺带展示一下」的口子 —— 站点 ID 不是用户语言。
 */
export interface LockerByCode {
  /**
   * 柜机 ID。**这是全 C 端 `lockerId` 的唯一来源** ——
   * 需要它的动作只有两个：`13.7` 建单与 `13.12` 建预约。
   *
   * ⚠️ `number` 是对 Java `Long` 的有意收窄，理由同 `types/auth.ts` 的 `LoginUser.id`。
   */
  id: number

  /**
   * 柜机码 —— 与用户扫到的那个串对应（契约 §13.6 :1096）。
   *
   * ⚠️ 本页**不渲染它**：用户人就在柜机前，不需要再读一遍编号。
   */
  code: string

  /**
   * 站点 ID。⚠️ 本页不展示，见 `LockerByCode` 的说明。契约 §13.6 (:1096)。
   */
  siteId: number

  /**
   * 站点名 —— 柜机页的**主标题**。
   *
   * ⚠️ 站点 `DISABLED` **仍返回名字**（`:1096,:1101`）——
   * 这个名字回来了**不代表站点可用**，可不可用只看 `online`。
   */
  siteName: string

  /**
   * 位置描述 —— 柜机页的**副标题**（如 `B1 层 3 号电梯口`）。契约 §13.6 (:1097)。
   */
  position: string

  /**
   * 是否在线 —— `= locker.status == 1`（`:1097,:1101`，已按优先级链收敛）。
   *
   * ⚠️⚠️ **`false` 是正常响应，不是错误**（§13.6 :1103 逐字）。
   * 后端自己建议「小程序选柜页按 `online` / `cellAvailability` 置灰入口」。
   * 把它做成错误弹窗，等于把后端声明的正常响应当异常处理 ——
   * **而「拿到数据」意味着用户能看见「确实有这么台柜机、只是现在不能用」，这是有效信息。**
   *
   * ⚠️ 本字段与 `status` **不是冗余**：`online` 是后端收敛后的布尔，`status` 是原始码。
   * 页面**只读 `online`** 判可用性，不自己对 `status` 做集合判断 ——
   * 那是把后端的收敛逻辑抄一份到客户端（抄的那份会在后端加状态时静默过期）。
   */
  online: boolean

  /**
   * 柜机原始状态码（1 ONLINE / 2 OFFLINE / 3 FAULT / 4 MAINTAINING）。
   *
   * ⚠️ 页面**不用它做判断**（可用性只看 `online`）。它留在类型里是为了让
   * `online` 的来源可回查，以及给诊断留一个字段 —— **不是**一份「哪些状态算不可用」的清单。
   */
  status: LockerStatus

  /**
   * 四档余位。契约 §13.6 (:1098,:1101)。
   *
   * ⚠️ 余位为 0 是**正常响应**，对应 `13.7` / `13.12` 的 `8002` ——
   * 入口置灰并写明「该规格已满」，**不是错误态**。
   */
  cellAvailability: CellAvailability
}
