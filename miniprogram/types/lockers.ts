// `13.6` 扫码查柜机的**手写 DTO** —— 只做形状，没有行为。
//
// 契约：API设计文档.md §13.6 `GET /api/app/v1/lockers/by-code` (:965-977)
// 出处底稿：`docs/research/R1-api-mapping.md` §1「13.6 · 响应 data」
// 消费方：`docs/spec/01-entry-and-identity.md` §6（柜机页）、
//         `docs/spec/08-waiting-state.md` §2（移交进等待态的入参来源）。
//
// ⚠️ 本模块的位置归 `07` §3 **硬规则 3**（「`types/` 与 `api/` 一一对应 ——
// 一个端点模块配一个 DTO（§7）」）与 §7（类型来源）。对应的端点函数在同名的
// `api/` 模块里，**两者一一对应**：
//
//     types/lockers.ts   ← 形状（本文件，纯类型，编译后不产出可执行代码）
//     api/lockers.ts     ← 搬运（入参 → 请求 → 出参 DTO）
//
// ⚠️ **为什么值得分成两个文件**（本票第一版把 DTO 和请求函数写在了一起，
// review 按 §3 硬规则 3 指出）：类型层是**后端的形状**，请求层是**调用方式**，
// 两者的读者不同 —— 只想知道「这个端点回来什么」的人不该同时读到 `wx.*` 的调用，
// 而只关心「怎么调」的人也不该翻过 120 行契约注释。`types/auth.ts` 已是这个形状
// （`api/session.ts` 从它 `import type`），本模块与它对齐。
//
// ⚠️ 本模块遵守 `07` §7 的五条规则：不发明字段、不改字段名、不合并语义不同的字段、
// 可空显式标 `| null`、枚举值与后端逐字一致、**找不到契约依据的字段不写**。
// 中文映射属 `09` 文案层，**不进类型层**。

/**
 * 柜机状态枚举 —— **值与后端逐字一致**，不做任何中文映射（`07` §7 规则 4）。
 *
 * 契约：API设计文档.md §13.6 (:971)
 * 后端真源：`LockerStatus`；`online` 的口径就是 `status == ONLINE`（`:971,:977`，已按优先级链收敛）。
 *
 * ⚠️ 中文映射属 `09` 文案层，**不进这里**：类型层是后端的形状，文案层是用户的语言。
 * 柜机页上要显示的不是这四个枚举名，而是 `09` §7.2 那一行「这台柜机暂时不可用」。
 */
export type LockerStatus = 'ONLINE' | 'OFFLINE' | 'FAULT' | 'MAINTAINING'

/**
 * 三档余位计数 —— `{ small, medium, large }`（契约 §13.6 :972）。
 *
 * 契约：API设计文档.md §13.6 (:972,:977)
 * 出处底稿：`R1` §1「13.6 · 响应 data」`cellAvailability` 行 + 陷阱表
 *
 * ⚠️⚠️ **阶名是小写**（`small` / `medium` / `large`），与 `13.7` 请求体里的
 * `cellType` 枚举（**大写** `SMALL` / `MEDIUM` / `LARGE`）**不是同一套写法**。
 * 这不是笔误，是契约原样（`:972` 的 `{ small, medium, large }`）——
 * 把它们当成同一个枚举名复用会在运行时静默取到 `undefined`（`availability['SMALL']` → 空）。
 * 两者的转换由页面负责（见 `pages/locker/locker.ts` 的档位表）。
 *
 * ⚠️ **柜机非 `ONLINE` 时三项恒为 0 且不报错**（`:975,:977`）——
 * 那是**正常响应而非错误**。⇒ 类型上它就是 `number`，**不是** `number | null`：
 * 「0」是一个有意义的、服务端明确回显过的值（该规格已满），把它当缺失处理会
 * 让页面走上「数据没回来」那条路，而用户看到的是一个错误态。
 */
export interface CellAvailability {
  /** 小格口空闲计数。⚠️ 小写阶名，见上。契约 §13.6 (:972)。 */
  small: number
  /** 中格口空闲计数。⚠️ 小写阶名，见上。契约 §13.6 (:972)。 */
  medium: number
  /** 大格口空闲计数。⚠️ 小写阶名，见上。契约 §13.6 (:972)。 */
  large: number
}

/**
 * `13.6` 响应 `data` —— 一台柜机的全部可得信息。
 *
 * 契约：API设计文档.md §13.6 (:966-977)
 *
 * ```json
 * { "id": 11, "code": "WD-01", "siteId": 3, "siteName": "望京 SOHO T1",
 *   "position": "B1 层 3 号电梯口", "online": true, "status": "ONLINE",
 *   "cellAvailability": { "small": 4, "medium": 2, "large": 0 } }
 * ```
 *
 * ⚠️ **`siteId` 有，但本页不用**（`01` §6 的渲染清单里没有它）。
 * 它留在类型里是为了**如实反映后端形状**（`07` §7 规则 2「不发明、不改名」），
 * 而不是给实现者一个「顺带展示一下」的口子 —— 站点 ID 不是用户语言（`09` §8）。
 */
export interface LockerByCode {
  /**
   * 柜机 ID。**这是全 C 端 `lockerId` 的唯一来源**（`01` §1.2）——
   * 需要它的动作只有两个：`13.7` 建单与 `13.12` 建预约（`01` §1.3）。
   *
   * ⚠️ `number` 是对 Java `Long` 的有意收窄，理由同 `types/auth.ts` 的 `LoginUser.id`。
   */
  id: number

  /**
   * 柜机码 —— 与用户扫到的那个串对应（契约 §13.6 :970）。
   *
   * ⚠️ 本页**不渲染它**：`09` §8 明令用户可见位置不出现 `lockerCode` 这个字段名，
   * 而柜机码本身在柜机页上没有用处（用户人就在柜机前，不需要再读一遍编号）。
   */
  code: string

  /**
   * 站点 ID。⚠️ 本页不展示，见 `LockerByCode` 的说明。契约 §13.6 (:970)。
   */
  siteId: number

  /**
   * 站点名 —— 柜机页的**主标题**（`01` §6 的渲染清单第一项）。
   *
   * ⚠️ 站点 `DISABLED` **仍返回名字**（`:970,:977`：需求 §3.1「停用不挡营业」）——
   * 也就是说这个名字**回来了就不代表站点可用**，可不可用只看 `online` / `status`。
   */
  siteName: string

  /**
   * 位置描述 —— 柜机页的**副标题**（如 `B1 层 3 号电梯口`，`01` §6）。
   *
   * 契约 §13.6 (:971)。不可空。
   */
  position: string

  /**
   * 是否在线 —— `= locker.status == ONLINE`（`:971,:977`，已按优先级链收敛）。
   *
   * ⚠️⚠️ **`false` 是正常响应，不是错误**（§16 #29 :1359 逐字，`R1` 陷阱表同）。
   * 后端自己建议「小程序选柜页按 `online` / `cellAvailability` 置灰入口」。
   * 把它做成错误弹窗，等于把后端声明的正常响应当异常处理 ——
   * **而「拿到数据」意味着用户能看见「确实有这么台柜机、只是现在不能用」，这是有效信息。**
   *
   * ⚠️ 本字段与 `status` **不是冗余**（虽然一期的口径让它们同步）：
   * `online` 是后端收敛后的布尔，`status` 是原始枚举。页面**只读 `online`** 判可用性，
   * 不自己对 `status` 做集合判断 —— 那是把后端的收敛逻辑抄一份到客户端
   * （抄的那份会在后端加一个状态时静默过期）。
   */
  online: boolean

  /**
   * 柜机原始状态枚举。契约 §13.6 (:971)。
   *
   * ⚠️ 页面**不用它做判断**（可用性只看 `online`，见上）。它留在类型里是为了让
   * `online` 的来源可回查，以及给诊断留一个字段 —— **不是**一份「哪些状态算不可用」的清单。
   */
  status: LockerStatus

  /**
   * 三档余位。契约 §13.6 (:972,:977)。
   *
   * ⚠️ 余位为 0 是**正常响应**，对应 `13.7` / `13.12` 的 `8002`
   * （`01` §6.1、`05` §3.4）—— 入口置灰并写明「该规格已满」，**不是错误态**。
   */
  cellAvailability: CellAvailability
}
