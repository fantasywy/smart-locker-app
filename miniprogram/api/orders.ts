// `13.7` 创建存件订单 —— 手写 DTO + 请求函数，**只做搬运**（`07` §3 硬规则 2）。
//
// 契约：API设计文档.md §13.7 `POST /api/app/v1/orders` (:979-998)
// 出处底稿：`docs/research/R1-api-mapping.md` §1「13.7 · 请求字段 / 响应 data / 错误码」
// 消费方：`docs/spec/01-entry-and-identity.md` §6（柜机页的「开始存件」）、
//         `docs/spec/08-waiting-state.md` §2（移交进等待态的唯一合法入参来源）。
//
// ⚠️ **`api/` 不含业务分支**（`07` §3 硬规则 2）。「`4004` 该说什么」「`8002` 该说什么」
// 是 `04` §9 的文案裁决，落在页面；本模块只把异常对象交出去。
//
// ⚠️⚠️ **`13.7` 不幂等**（`R1` §1「13.7 · 幂等性」逐字：
// 「**不幂等** —— 每次调用创建新订单 + 新预留格口。前端须防止重复提交」）。
// 这是本端点与 `13.11`（幂等，可安全重试）的**根本差别**，也是页面必须有
// 技术性防抖的原因 —— 而那条防抖是 `09` §5.8 硬规则 5 明确允许的**唯一两种禁用之一**
// （「请求进行中的技术性防抖」）。

import type { RequestResult } from '../request/types'
import { API_PREFIX } from '../request/config'
import { request } from '../request/index'

/** `13.7` 的路径 —— `POST /api/app/v1/orders`（契约 §13.7 :979）。 */
export const CREATE_ORDER_PATH = `${API_PREFIX}/orders`

/**
 * 格口类型枚举 —— **值与后端逐字一致**，不做任何中文映射（`07` §7 规则 4）。
 *
 * 契约：API设计文档.md §13.7 (:984)
 *
 * ⚠️⚠️ **它是大写的，而 `13.6` 的 `cellAvailability` 阶名是小写的**
 * （`{ small, medium, large }`，`:972`）。两者**不是同一套写法**，
 * 不能互相 `[]` 取用（`availability['SMALL']` 会静默取到 `undefined`）。
 * 这个转换由页面的一处档位表负责 —— 类型层在这里如实保留契约的两种写法，
 * 不做「顺手归一」：归一了就看不出契约本身是不一致的。
 *
 * ⚠️ 中文显示（小 / 中 / 大）属 `09` 文案层（`09` §8 禁用词表：枚举名不进用户文案）。
 */
export type CellType = 'SMALL' | 'MEDIUM' | 'LARGE'

/**
 * `13.7` 请求体 —— `POST /api/app/v1/orders`。
 *
 * 契约：API设计文档.md §13.7 (:982-984)
 *
 * ```json
 * { "lockerId": 11, "cellType": "MEDIUM" }
 * ```
 *
 * ⚠️ 只有两个字段，**一个都不多**：契约里没有「备注」「数量」「预约时长」之类。
 * 柜机页的三档入口各发一次这个请求，用户选的是**规格**，不是格口 ——
 * 具体分配哪个格口由服务端在事务里做（`FREE → RESERVED`，`:995`）。
 */
export interface CreateOrderRequest {
  /**
   * 柜机 ID —— **只能来自 `13.6` 的响应**（`01` §1.2：它是 `lockerId` 的唯一来源）。
   *
   * ⚠️ 客户端**不得**从任何别处编一个：ADR-0001 已裁决 C 端不做柜机浏览，
   * `lockerId` 的长相（自增主键）客户端无从推导，猜一个等于把订单下到别的柜机上。
   */
  lockerId: number

  /**
   * 格口规格 —— 用户点的是**哪一档入口**（小 / 中 / 大）。
   *
   * ⚠️ 用户看到的按钮文案由 `09` 定（小 / 中 / 大），发出去的枚举是这一套大写值。
   */
  cellType: CellType
}

/**
 * `13.7` 响应 `data` —— 建单成功后的订单摘要。
 *
 * 契约：API设计文档.md §13.7 (:986-990)
 *
 * ```json
 * { "orderId": 1001, "orderNo": "20250401001", "cellNo": "M05", "openTimeoutMinutes": 10 }
 * ```
 */
export interface CreateOrderResponse {
  /**
   * 订单 ID —— **等待态的入参**（`08` §2 三条入口一律携带它）。
   *
   * ⚠️ `number` 是对 Java `Long` 的有意收窄，理由同 `types/auth.ts` 的 `LoginUser.id`。
   */
  orderId: number

  /**
   * 订单号（如 `20250401001`）。契约 §13.7 (:990)。
   *
   * ⚠️ **本页不用它**，等待态也不用（`08` §8：等待态不倒计时、不展示单号）。
   * 契约里有就带住，`09` §8 明令 `orderNo` 不展示给用户。
   */
  orderNo: string

  /**
   * 服务端分配的格口号（如 `M05`）。契约 §13.7 (:990)。
   *
   * ⚠️ **本页与等待态都不展示它**：`09` §8 明令「`cellNo` 仅作行内定位辅助」
   * （`03` §5 的订单列表行用法），**不给它中文名**，也不在等待态出现 ——
   * 用户此刻人就在柜机前，格口号帮不上忙，而 `cellNo` 的展示位置在订单行。
   */
  cellNo: string

  /**
   * 开门超时分钟数 —— **`openTimeoutMinutes` 唯一的合法来源**（`08` §1.7 逐字：
   * 「只在 `13.7` 建单响应里」；`05` §1.2 同：转单与支付路径都拿不到它）。
   *
   * 契约：API设计文档.md §13.7 (:990)：取 `order.openTimeoutMinutes`（缺省 10）。
   *
   * ⚠️⚠️ **两条硬约束同时落在这个字段上**（票面逐字：本字段「唯一的合法来源与
   * 唯一合法使用位置」）：
   *
   * 1. **不硬编码、不猜。** 缺省值 10 是**后端的**缺省，不是客户端的常量 ——
   *    运营可以在后台改它。客户端写一个 10 就等于**在服务端改了配置之后继续撒谎**。
   * 2. **它唯一合法的去向是作为页面参数传给等待态**（`redirectTo` 的 query）。
   *    ⚠️ 它**没有任何合法的展示位置**（`04` §11 就地补正 + `09` §5.8 硬规则 4：
   *    「绝不倒计时、绝不显示分钟数」；`08` §8 已把等待态的倒计时判死）。
   *    也就是说：这个数字在界面上**一个字都不能出现**，它只用于把基准交给下一个页面。
   */
  openTimeoutMinutes: number
}

/**
 * `13.7` 创建存件订单 —— 分配一个空闲格口并生成开门指令。
 *
 * @param body `lockerId`（来自 `13.6`）+ `cellType`（用户点的那一档）
 * @returns 成功时订单摘要（含 `orderId` 与 `openTimeoutMinutes`）；失败时统一异常对象
 *
 * ⚠️ **失败码归因在页面**（`04` §9 / `09` §7.2）：
 *   • `4004` → 「这台柜机暂时不可用，请换一台或稍后再试」（`04` §9 逐字）
 *   • `8002` → 「该类型格口已满，换一种类型或换一台柜机」（`04` §9 逐字）
 *   • `5004` → 走受限卡（`07` §4.2 的**唯一特判**，请求层已归一成 `kind: 'restricted'`）
 *
 * ⚠️ **本函数不幂等**：它每被调用一次就多一张订单 + 一个预留格口（见文件头）。
 * 调用方必须自己防重复提交。
 */
export function createOrder(
  body: CreateOrderRequest,
): Promise<RequestResult<CreateOrderResponse>> {
  return request<CreateOrderResponse>(CREATE_ORDER_PATH, {
    method: 'POST',
    data: body,
  })
}
