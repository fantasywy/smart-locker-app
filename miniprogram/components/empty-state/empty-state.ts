// **空态** —— 三个列表页共用的那一块「什么都没有」。
//
// 契约出处：`docs/spec/09-copy-and-status.md` §7.1（三个空态**逐字**）；
// 消费方出处：`03` §9（订单列表）、`05` §2（预约列表）、`04` §7.3（信用分明细）。
// 形态出处：`07` §3 把「空态」列为 `components/` 成员。
//
// ## 本票（#23）的裁决：**做成参数化组件**，不做成三份
//
// 票面说「若三处差异大于共性，各写各的也可接受」，并要求把结论记进 resolution。
// 逐条对照 `09` §7.1 那三行之后，**共性是结构级的、差异全是数据**：
//
// | | 订单列表 | 预约列表 | 信用分明细 |
// |---|---|---|---|
// | 标题 | 还没有订单 | 还没有预约 | 还没有分数变动 |
// | 说明句 | 扫码存件，把东西放进柜子 | 到柜机前扫码后可以预约使用时段 | **（无）** |
// | 主行动 | 〔扫码存件〕 | 〔扫码存件〕 | **（无）** |
//
// ⇒ 结构只有一条：**标题 +（可选）说明句 +（可选）主行动**。三处的差异全落在
// 「哪几个槽位有值」上，没有一处需要不同的排布、不同的层级、不同的元素种类。
// 那不是「三个不同的空态」，那是**同一个空态的三组数据**。
//
// ⚠️ 反过来说，若真做成三份，最先分叉的一定是**主行动那条路**：订单与预约的空态
// 出口是**同一个动作**（`扫码存件` → `wx.scanCode` → 柜机页），而且 `03` §9 明写
// 「复用顶部常驻入口」、`05` §2 明写出口**只能是扫码**（「新建预约」不成立 ——
// `lockerId` 的唯一来源是扫码）。三份实现里只要有一份把扫码写成 `navigateTo`、
// 或者写成「新建预约」，用户就走进一条走不通的路。
//
// ## 三条裁决
//
// 1. **文案由调用方从 `startup/copy.ts` 传进来，组件不持有任何文案字面量。**
//    `09` §0 硬规则 1：用户可见的每个字归文案层。组件若自带一句默认文案，
//    那句就脱离了 `USER_VISIBLE_COPY_LITERALS` 的反推守卫（`conventions.test.ts`）。
//    ⇒ `title` 是**必填**属性，没有 `value` 默认值 —— 少填一个标题是编译期/运行期
//    立刻可见的错，而不是屏上一片空白。
//
// 2. ⚠️ **主行动只发事件，不自己 `wx.scanCode`。**
//    与 `navigation-bar.home()` 的选择**刚好相反**，理由也刚好相反：
//    `home()` 的目标是**唯一**的（订单 tab），组件可以且应当自己完成；
//    而空态的两个动作（`scan` / `reserve`）要跳到**别的页面**、而柜机页还认一个
//    `code` 参数（`01` §6），组件不知道当前页面栈 —— 替调用方决定就是替它编一个
//    它没说的东西。⇒ 组件给的是**按钮**，跳转归页面。
//
// 3. **空态只画内容，不画「整页空」的版式。** 它出现在列表区域**内部**——
//    列表页的导航栏、以及订单列表顶部那条常驻「扫码存件」入口（`01` §2.3）
//    都在它外面、始终在屏上。做成整页空会让那两个出口在空态下消失。
//
// ## 视觉层的两处裁决（都在 `empty-state.scss` 里落地，出处一并记在这里）
//
// 4. ⚠️ **主行动用 `<button>`，不是 `<view>` + `bindtap`。**
//    `failure-exit` 的静态出口用的是 `<view>`（那是**次要**出口，且里面混着
//    `open-type="contact"` 的原生按钮）；而空态的主行动是这一屏**唯一**的动作 ——
//    `<button>` 给的是原生的可点目标语义与无障碍角色（`aria-role` 之外还有真实的
//    按钮语义），这在「一个空屏上只做一件事」的场合值得那两行 `::after` reset
//    （小程序 `<button>` 自带一层边框）的代价。`04` §8 的客服也走的 `<button>`。
//
// 5. ⚠️ **按下态用 `$color-primary-hover`，不是 `$color-primary-active`**（`10` §3.1）。
//    `_variables.scss` 给这两个 token 分了不同的语义：`-hover` 是「按下态」
//    （注释逐字：「按下态（小程序无 hover，留给『按下』反馈）」），`-active` 是
//    「正常/激活档」，它同时是**绿色文字的 ink**（白底 4.62）与「白字压绿底」的底色。
//    拿 ink 当按下态底色是两回事，且会与 `failure-exit__retry` 的按下态分叉 ——
//    同一个概念两个 token，正是 `10` §3 想避免的那种漂移。
//
// ⚠️ **尺寸单位照 `10` §7.2**（布局几何 `rpx` / 字号与 1px 细节 `px`）——
//    本仓库**没有**守卫查这一条（`verify-visual-tokens.mjs` 的 68 条断言里一条都不查），
//    所以 #23 的 review 抓到过一次 `px` 误用。改样式时请对着 §7.2 再核一遍。

Component({
  properties: {
    /**
     * 空态标题 —— `09` §7.1 每一行的第一句。
     *
     * ⚠️ **必填**（没有 `value` 默认值）。一个默认标题意味着「忘了传」会静默渲染成
     * 那句默认值 —— 而三个空态的标题**互不相同**，任何默认值在其中两处都是错的。
     */
    title: {
      type: String
    },

    /**
     * 说明句 —— 可选。信用分明细**没有**这一句（`09` §7.1 那一行只有标题）。
     *
     * ⚠️ 空串 = 不渲染。不要为了「凑齐两行」给它编一句话 —— 用户可见的字要么能
     * 在 `09` 查到出处，要么就是缺口（`09` §0 硬规则 1、`map #21` Notes 第 3 条）。
     */
    hint: {
      type: String,
      value: ''
    },

    /**
     * 主行动按钮文案 —— 可选。信用分明细**没有**主行动（`04` §7.3 没定，也确无动作可做）。
     *
     * ⚠️ 订单列表与预约列表这里都是 `扫码存件`（`09` §7.1 两行逐字）——
     * 同一个动作在全局只有一个名字（`09` §5.6 规则 7）。别在预约空态里写
     * 「新建预约」：`05` §2 已裁决出口**只能是扫码**（`lockerId` 唯一来源是扫码）。
     */
    actionLabel: {
      type: String,
      value: ''
    }
  },

  methods: {
    /**
     * 主行动点击 —— **只把动作交回页面**（见文件头裁决 2）。
     *
     * ⚠️ 事件名不带参数：动作的选择器是**哪一个按钮**，而当前只有这一个按钮。
     * 加一个 `{ action: 'scan' }` 的载荷等于现在就开始为「将来可能有第二个按钮」
     * 设计 —— 而那第二个按钮（预约空态的「新建预约」）已经被 `05` §2 判死了。
     *
     * ⚠️ **它没有 `fail` 分支要处理，与 `navigation-bar.home()` 不同**：这里只发一个
     * 本地事件，不做任何可能失败的 I/O。真正的跳转（`wx.scanCode` + 进柜机页）
     * 在页面里，那里才需要管失败 —— 本组件因此连 `wx` 都不碰（见文件头裁决 2）。
     */
    onAction(): void {
      this.triggerEvent('action')
    }
  }
})
