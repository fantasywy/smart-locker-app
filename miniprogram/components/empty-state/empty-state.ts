// **空态** —— 列表页共用的那一块「什么都没有」。
//
// ## 对外契约（#59 换 Vant 实现时**刻意不变**）
//
// | 入参 | 必填 | 说明 |
// |---|---|---|
// | `title` | ✅ | 空态标题；没有默认值，忘了传就立刻可见 |
// | `hint` |  | 说明句；空串 = 不渲染（信用分明细只有标题） |
// | `actionLabel` |  | 主行动按钮文案；空串 = 不渲染 |
//
// 事件只有 `action`，**不带载荷**：动作的选择器是「哪一个按钮」，而当前只有一个。
//
// ## 三条裁决
//
// 1. **文案由调用方从 `startup/copy.ts` 传进来，组件不持有任何文案字面量。**
//    用户可见的每个字归文案层；组件若自带默认标题，那句就脱离了
//    `USER_VISIBLE_COPY_LITERALS` 的反推守卫。⇒ `title` 必填、无默认值。
//
// 2. ⚠️ **主行动只发事件，不自己 `wx.scanCode`。**
//    与 `navigation-bar.home()` / `orders()` 的选择**刚好相反**：那两个的目标是唯一的
//    （首页 / 订单列表），组件可以且应当自己完成；而空态的动作要跳**别的页面**、
//    柜机页还认一个 `code` 参数 —— 组件不知道当前页面栈，替调用方决定就是替它编
//    一个它没说的东西。⇒ 组件给的是按钮，跳转归页面。
//
// 3. **空态只画内容，不画「整页空」的版式。** 它出现在列表区域内部 ——
//    页面导航栏与常驻入口都在它外面、始终在屏上。
//
// ## 视觉层（#59）
//
// 4. 内部由 `van-empty`（`image=""` 关掉远端默认图）+ `van-button` 承载；
//    标题 / 说明放在 `description` slot 里，标题 main、说明 sub（描述色的全局覆盖
//    在 `app.scss`，本组件不重复主题映射）。
// 5. 组件根节点显式设 `$color-text-main` —— 不得依赖继承（`_variables.scss` 硬规则 1）。
// 6. 可点目标 ≥ 44px（88rpx @375pt），与 `failure-exit__retry` 同一把尺子。

Component({
  properties: {
    /**
     * 空态标题 —— 每个空态的第一句。
     *
     * ⚠️ **必填**（没有 `value` 默认值）。一个默认标题意味着「忘了传」会静默渲染成
     * 那句默认值 —— 而三个空态的标题**互不相同**，任何默认值在其中两处都是错的。
     */
    title: {
      type: String,
    },

    /**
     * 说明句 —— 可选。信用分明细**没有**这一句（它只有标题）。
     *
     * ⚠️ 空串 = 不渲染。不要为了「凑齐两行」给它编一句话 ——
     * 用户可见的字要么在 `startup/copy.ts` 里有出处，要么就是缺口。
     */
    hint: {
      type: String,
      value: '',
    },

    /**
     * 主行动按钮文案 —— 可选。信用分明细**没有**主行动。
     *
     * ⚠️ 订单列表与预约列表这里都是 `扫码存件`（同一个动作，全局只有一个名字）。
     * 预约空态**不是**「新建预约」—— 创建入口只在柜机页（`lockerId` 唯一来源是扫码）。
     */
    actionLabel: {
      type: String,
      value: '',
    },
  },

  methods: {
    /**
     * 主行动点击 —— **只把动作交回页面**（见文件头裁决 2）。
     *
     * ⚠️ 没有 `fail` 分支：这里只发一个本地事件，不做任何可能失败的 I/O。
     * 真正的跳转（`wx.scanCode` + 进柜机页）在页面里，那里才需要管失败。
     */
    onAction(): void {
      this.triggerEvent('action')
    },
  },
})

// 显式标记为模块：本文件目前没有 import/export，但测试用动态 import 读取
// `Component()` 的定义对象；不加这一行时 TS 把文件当全局脚本，报「不是模块」。
export {}
