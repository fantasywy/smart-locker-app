// **骨架屏** —— 冷启动时「页面结构先出现、数据区等 token」的那一半。
//
// ## ⚠️ 变体数量与 spec §11 的差异（有意，且逐票有据）
//
// spec §11 的组件表只列了四个变体（`list` / `home` / `detail` / `nearby`）。
// 实现期按各页面票**扩到了七个**，每一条都有对应票的验收要求，不是顺手加的：
//
//   • `list`（#20）—— 列表页骨架，spec §11 列的四个之一；
//   • `home`（#61）—— 首页整页同构骨架（品牌块 / 圆按钮 / 一卡 / 入口条），spec §2 要求；
//   • `detail`（#64）—— 订单详情骨架（状态块 / 取件码块 / 两行信息 / 时间轴），spec §7 要求；
//   • `nearby`（#72）—— 附近页骨架（搜索行 + 三张站点卡），spec §8 要求；
//   • `card`（#67）—— 首页进行中订单区的「一张卡」骨架：与整页骨架不同，
//     它只替换订单区，品牌区与扫码按钮立即可用（spec §2）；
//   • `identity` / `credit`（#69）—— 「我的」页身份区与信用分卡**各自**骨架：
//     spec §9 要求两块互不阻塞（一块失败不塌整页），共用一张骨架会说谎。
//
// ⇒ 差异记在这里（一次说清），而不是让每个读者去比对 spec 表与实现。
// 行为没有额外分支：七个变体只是七套形状，判定条件一个都没多。
//
// ## 三条裁决
//
// 1. **纯图形占位，无文字**。⚠️ **不得放「加载中」文字盖住骨架** ——
//    所以本组件的 `data` 里**没有**任何文字字段，wxml 里也没有 `{{ }}` 文本节点。
//    这不是省事，是那条禁令在结构上的落地：组件**没有**能放文案的地方。
//
// 2. **形状对照真实版式**：列表行 = 色条 + 两行短块 + 状态标签位。
//    本组件按这个形状出占位块 —— 骨架屏的价值全在「布局不跳」，
//    形状对不上真版式时它比白屏更糟（内容一到位整页重排）。
//    `variant="home"` 是 #61 的首页版式：品牌块 / 圆按钮 / 一卡 / 入口条。
//
// 3. ⚠️ **首屏加速靠骨架屏，不靠数据缓存**。骨架屏是**空**的 ——
//    它没有任何「上次的数据」可以显示，也不该有。取件码与订单状态属「看到就必须是真的」
//    的数据，缓存说谎（用户拿着过期取件码走到柜机前）比空白更糟。
//    ⇒ 本组件**不接**任何数据属性，连一个 `items` 都不收。
//
// ⚠️ 它**不自己判断加载态**：显示与否由页面按闸门的 `phase` 决定。组件只画形状，
// 不做「if 加载中」这种判断 —— 状态归闸门（`startup/gate.ts`）一处持有。

import { SKELETON_ROW_COUNT } from '../../startup/copy'

Component({
  properties: {
    /**
     * 版式变体 —— **只描述形状，不携带数据**。
     *
     * ⚠️ 缺省 `list` 保持 #20 的列表骨架行为；`home` 是 #61 首页同构骨架；
     * `card` 是 #67 首页进行中订单区的「一张卡」骨架；`identity` / `credit` 是
     * #69「我的」页身份区与信用分卡的两份骨架（spec §9 要求两块**各自**骨架）；
     * `detail` 是 #64 订单详情骨架；`nearby` 是 #72 附近页的搜索行 + 三张站点卡骨架。
     */
    variant: {
      type: String,
      value: 'list',
    },
  },

  /**
   * 组件不持有状态、不接数据。
   *
   * ⚠️ 连「几行」这个数字都从 `startup/copy.ts` 来（`SKELETON_ROW_COUNT`），
   * 不在 wxml 里写 `wx:for="{{[1,2,3]}}"` —— 那种写法在数据区真的落地三行之后
   * 会悄悄不同步，而骨架屏形状漂移的代价正是「内容一到位整页重排」。
   */
  data: {
    rows: Array.from({ length: SKELETON_ROW_COUNT }, (_, index) => index),
  },
})
